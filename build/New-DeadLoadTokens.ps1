<#
    .SYNOPSIS
        Generates the DeadLoad design tokens for the website (CSS custom properties) and the
        tray app (C# constants) from design/tokens.json.

    .DESCRIPTION
        design/tokens.json is the single source of colors, type, spacing, radius, focus and
        motion (docs/design/IMPLEMENTATION-PLAN.md decision 7). This script writes:

          site/assets/css/tokens.css   light values on :root, dark values under
                                       prefers-color-scheme: dark (unless the page forces
                                       data-theme="light") and under [data-theme="dark"],
                                       plus a forced-colors block that hands color to the system.
          src/tray/Ui/Theme.g.cs       namespace DeadLoad.Tray.Ui, static class ThemeTokens with
                                       Light*/Dark* Color fields, spacing, radius, focus and fonts.

        Output is 7-bit ASCII, UTF-8 without a byte order mark, in token order, so re-running the
        script produces byte-identical files (CSS with LF, C# with CRLF, as .gitattributes says).

    .PARAMETER TokensPath
        The token file (default: <repo>\design\tokens.json).

    .PARAMETER CssPath
        Output CSS file (default: <repo>\site\assets\css\tokens.css).

    .PARAMETER CSharpPath
        Output C# file (default: <repo>\src\tray\Ui\Theme.g.cs).

    .OUTPUTS
        System.IO.FileInfo for each file written.

    .EXAMPLE
        pwsh -NoProfile -File build\New-DeadLoadTokens.ps1
#>
[CmdletBinding(SupportsShouldProcess)]
param
(
    [string]$TokensPath,
    [string]$CssPath,
    [string]$CSharpPath
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version 2.0

$repoRoot = Split-Path -Path $PSScriptRoot -Parent
if (-not $TokensPath) { $TokensPath = Join-Path $repoRoot 'design\tokens.json' }
if (-not $CssPath) { $CssPath = Join-Path $repoRoot 'site\assets\css\tokens.css' }
if (-not $CSharpPath) { $CSharpPath = Join-Path $repoRoot 'src\tray\Ui\Theme.g.cs' }

$tokens = [System.IO.File]::ReadAllText($TokensPath) | ConvertFrom-Json

function ConvertTo-DLKebab
{
    # brandNavy -> brand-navy, webH2 -> web-h2
    param ([string]$Name)

    return ([regex]::Replace($Name, '([a-z0-9])([A-Z])', '$1-$2')).ToLowerInvariant()
}

function ConvertTo-DLPascal
{
    param ([string]$Name)

    return $Name.Substring(0, 1).ToUpperInvariant() + $Name.Substring(1)
}

function Get-DLProperty
{
    # Property order of the JSON object, the same on 5.1 and 7.
    param ([object]$Object)

    return @($Object.PSObject.Properties | Where-Object { $_.MemberType -eq 'NoteProperty' })
}

function Test-DLHexColor
{
    param ([string]$Name, [string]$Value)

    if ($Value -notmatch '^#[0-9A-Fa-f]{6}$') { throw ('Color {0} is not #RRGGBB: {1}' -f $Name, $Value) }
}

function ConvertTo-DLFontStack
{
    param ([object[]]$Families)

    $parts = foreach ($family in $Families)
    {
        $text = [string]$family
        if ($text -match '\s') { '"' + $text + '"' } else { $text }
    }
    return ($parts -join ', ')
}

$lightColors = Get-DLProperty -Object $tokens.color.light
$darkColors = Get-DLProperty -Object $tokens.color.dark
$lightNames = @($lightColors | ForEach-Object { $_.Name })
$darkNames = @($darkColors | ForEach-Object { $_.Name })
if (($lightNames -join ',') -ne ($darkNames -join ',')) { throw 'Light and dark colors must name the same tokens in the same order.' }
foreach ($p in $lightColors) { Test-DLHexColor -Name ('light.' + $p.Name) -Value $p.Value }
foreach ($p in $darkColors) { Test-DLHexColor -Name ('dark.' + $p.Name) -Value $p.Value }

# ---------------------------------------------------------------- CSS
$css = New-Object 'System.Collections.Generic.List[string]'
$css.Add('/* Generated by build/New-DeadLoadTokens.ps1 from design/tokens.json; do not edit. */')
$css.Add('')
$css.Add(':root {')
$css.Add('  color-scheme: light dark;')
foreach ($p in $lightColors) { $css.Add(('  --dl-color-{0}: {1};' -f (ConvertTo-DLKebab -Name $p.Name), $p.Value.ToUpperInvariant())) }
foreach ($p in (Get-DLProperty -Object $tokens.font))
{
    if ($p.Name -eq 'weight' -or $p.Name -eq 'sizePx') { continue }
    $css.Add(('  --dl-font-{0}: {1};' -f (ConvertTo-DLKebab -Name $p.Name), (ConvertTo-DLFontStack -Families @($p.Value))))
}
foreach ($p in (Get-DLProperty -Object $tokens.font.weight)) { $css.Add(('  --dl-weight-{0}: {1};' -f (ConvertTo-DLKebab -Name $p.Name), $p.Value)) }
foreach ($p in (Get-DLProperty -Object $tokens.font.sizePx)) { $css.Add(('  --dl-size-{0}: {1}px;' -f (ConvertTo-DLKebab -Name $p.Name), $p.Value)) }
$space = @($tokens.space)
for ($i = 0; $i -lt $space.Count; $i++) { $css.Add(('  --dl-space-{0}: {1}px;' -f $i, $space[$i])) }
foreach ($p in (Get-DLProperty -Object $tokens.radius)) { $css.Add(('  --dl-radius-{0}: {1}px;' -f (ConvertTo-DLKebab -Name $p.Name), $p.Value)) }
$css.Add(('  --dl-border-width: {0}px;' -f $tokens.border.width))
$css.Add(('  --dl-focus-width: {0}px;' -f $tokens.focus.width))
$css.Add(('  --dl-focus-offset: {0}px;' -f $tokens.focus.offset))
foreach ($p in (Get-DLProperty -Object $tokens.control)) { $css.Add(('  --dl-control-{0}: {1}px;' -f (ConvertTo-DLKebab -Name $p.Name), $p.Value)) }
foreach ($p in (Get-DLProperty -Object $tokens.motion)) { $css.Add(('  --dl-motion-{0}: {1}ms;' -f (ConvertTo-DLKebab -Name $p.Name), $p.Value)) }
$css.Add(('  --dl-layout-web-max-width: {0}px;' -f $tokens.layout.webMaxWidth))
$css.Add('}')
$css.Add('')

$darkBlock = New-Object 'System.Collections.Generic.List[string]'
foreach ($p in $darkColors) { $darkBlock.Add(('--dl-color-{0}: {1};' -f (ConvertTo-DLKebab -Name $p.Name), $p.Value.ToUpperInvariant())) }

# The system preference applies unless the page pins a theme with data-theme.
$css.Add('@media (prefers-color-scheme: dark) {')
$css.Add('  :root:not([data-theme="light"]) {')
$css.Add('    color-scheme: dark;')
foreach ($line in $darkBlock) { $css.Add('    ' + $line) }
$css.Add('  }')
$css.Add('}')
$css.Add('')
$css.Add(':root[data-theme="dark"] {')
$css.Add('  color-scheme: dark;')
foreach ($line in $darkBlock) { $css.Add('  ' + $line) }
$css.Add('}')
$css.Add('')
$css.Add(':root[data-theme="light"] {')
$css.Add('  color-scheme: light;')
$css.Add('}')
$css.Add('')
# High contrast: the system palette wins; brand colors map to system colors so nothing is lost.
$css.Add('@media (forced-colors: active) {')
$css.Add('  :root {')
$forced = [ordered]@{
    'brand-navy'     = 'CanvasText'
    'brand-blue'     = 'LinkText'
    'slate'          = 'CanvasText'
    'concrete'       = 'GrayText'
    'canvas'         = 'Canvas'
    'card'           = 'Canvas'
    'raised'         = 'Canvas'
    'border'         = 'CanvasText'
    'text-primary'   = 'CanvasText'
    'text-secondary' = 'CanvasText'
    'text-muted'     = 'CanvasText'
    'success'        = 'CanvasText'
    'warning'        = 'CanvasText'
    'danger'         = 'CanvasText'
    'focus-ring'     = 'Highlight'
    'on-brand'       = 'ButtonText'
}
foreach ($p in $lightColors)
{
    $name = ConvertTo-DLKebab -Name $p.Name
    $system = 'CanvasText'
    if ($forced.Contains($name)) { $system = $forced[$name] }
    $css.Add(('    --dl-color-{0}: {1};' -f $name, $system))
}
$css.Add('  }')
$css.Add('}')

# ---------------------------------------------------------------- C#
$cs = New-Object 'System.Collections.Generic.List[string]'
$cs.Add('// <auto-generated>')
$cs.Add('// Generated by build/New-DeadLoadTokens.ps1; do not edit.')
$cs.Add('// Source: design/tokens.json (docs/design/DEADLOAD_DESIGN_SYSTEM.md section 4).')
$cs.Add('// </auto-generated>')
$cs.Add('using System.Drawing;')
$cs.Add('')
$cs.Add('namespace DeadLoad.Tray.Ui')
$cs.Add('{')
$cs.Add('    /// <summary>Design tokens for the DeadLoad window. High contrast uses SystemColors instead.</summary>')
$cs.Add('    internal static class ThemeTokens')
$cs.Add('    {')
foreach ($pair in @(@('Light', $lightColors), @('Dark', $darkColors)))
{
    foreach ($p in $pair[1])
    {
        $hex = $p.Value.Substring(1)
        $r = [Convert]::ToInt32($hex.Substring(0, 2), 16)
        $g = [Convert]::ToInt32($hex.Substring(2, 2), 16)
        $b = [Convert]::ToInt32($hex.Substring(4, 2), 16)
        $cs.Add(('        public static readonly Color {0}{1} = Color.FromArgb({2}, {3}, {4}); // {5}' -f $pair[0], (ConvertTo-DLPascal -Name $p.Name), $r, $g, $b, $p.Value.ToUpperInvariant()))
    }
    $cs.Add('')
}
for ($i = 0; $i -lt $space.Count; $i++) { $cs.Add(('        public const int Space{0} = {1};' -f $i, $space[$i])) }
$cs.Add('')
foreach ($p in (Get-DLProperty -Object $tokens.radius)) { $cs.Add(('        public const int Radius{0} = {1};' -f (ConvertTo-DLPascal -Name $p.Name), $p.Value)) }
$cs.Add(('        public const int BorderWidth = {0};' -f $tokens.border.width))
$cs.Add(('        public const int FocusWidth = {0};' -f $tokens.focus.width))
$cs.Add(('        public const int FocusOffset = {0};' -f $tokens.focus.offset))
foreach ($p in (Get-DLProperty -Object $tokens.control)) { $cs.Add(('        public const int Control{0} = {1};' -f (ConvertTo-DLPascal -Name $p.Name), $p.Value)) }
foreach ($p in (Get-DLProperty -Object $tokens.motion)) { $cs.Add(('        public const int Motion{0} = {1};' -f (ConvertTo-DLPascal -Name $p.Name), $p.Value)) }
$cs.Add('')
foreach ($p in (Get-DLProperty -Object $tokens.font.weight)) { $cs.Add(('        public const int FontWeight{0} = {1};' -f (ConvertTo-DLPascal -Name $p.Name), $p.Value)) }
foreach ($p in (Get-DLProperty -Object $tokens.font.sizePx))
{
    if ($p.Name -notlike 'app*') { continue }
    $cs.Add(('        public const int FontSize{0}Px = {1};' -f (ConvertTo-DLPascal -Name $p.Name), $p.Value))
}
foreach ($name in @('app', 'appDisplay', 'mono'))
{
    $families = @($tokens.font.$name | ForEach-Object { '"' + ([string]$_).Replace('\', '\\').Replace('"', '\"') + '"' })
    $cs.Add(('        public static readonly string[] Font{0} = new[] {{ {1} }};' -f (ConvertTo-DLPascal -Name $name), ($families -join ', ')))
}
$cs.Add('    }')
$cs.Add('}')

$files = [ordered]@{}
$files[$CssPath] = (($css -join "`n") + "`n")
$files[$CSharpPath] = (($cs -join "`r`n") + "`r`n")

$encoding = New-Object System.Text.UTF8Encoding($false)
foreach ($path in @($files.Keys))
{
    $text = $files[$path]
    if ($text -match '[^\x00-\x7F]') { throw ('{0} would contain a non-ASCII character.' -f $path) }
    if ($PSCmdlet.ShouldProcess($path, 'Write design tokens'))
    {
        [void][System.IO.Directory]::CreateDirectory((Split-Path -Path $path -Parent))
        [System.IO.File]::WriteAllText($path, $text, $encoding)
        Get-Item -LiteralPath $path
    }
}
